def celsius_ke_fahrenheit(suhu_celsius):
  """Mengkonversi suhu dari Celsius ke Fahrenheit."""
  # Rumus: (
  suhu_fahrenheit = (suhu_celsius * 9/5) + 32
  return suhu_fahrenheit

print(f"print(celsius_ke_fahrenheit(0)) # Output: {celsius_ke_fahrenheit(0)}")
print(f"print(celsius_ke_fahrenheit(100)) # Output: {celsius_ke_fahrenheit(100)}")  